#!/usr/bin/env node
// Builds audio/levels.json (per-sound playback gain + start trim) from the asset audit (work/audio_asset_audit.cjs).
// The files themselves are never re-encoded: the page multiplies each voice by the gain and starts it at the trim.
//   gain dB = role target LUFS - the file's momentary-max loudness (K-weighted 400 ms, LUFS), clamped to [-12, +18] dB;
//             a boost never takes the file's decoded sample peak past +1 dBFS (a file already over is not boosted) (role gains <= 0.65 and the master
//             volume keep every voice under the limiter threshold).
//   trim s  = leading silence (< -45 dBFS) minus 3 ms, for one-shots where latency matters (fire, knife, equip, steps,
//             impacts, UI, feedback, abilities, announcer, death, kill banners). Reload / inspect / ambient keep their
//             timing: their leading pause is part of the reload choreography.
// Usage: node work/audio_levels_build.cjs <audit.json>   (writes audio/levels.json)
'use strict';
const fs = require('fs'), path = require('path');
const root = path.resolve(__dirname, '..');
const man = JSON.parse(fs.readFileSync(path.join(root, 'audio/manifest.json'), 'utf8'));
const TARGET = { fire: -15, knife: -18, foley: -24, step: -20, impact: -18, ui: -20, voice: -18, death: -17, ability: -16, event: -15, feedback: -16, kill: -16, ambient: null };
const TRIM = new Set(['fire', 'knife', 'step', 'impact', 'ui', 'voice', 'death', 'ability', 'feedback', 'kill', 'event', 'equip']);
function role(key) {
  const k = key.split('/'), last = k[k.length - 1];
  if (k[0] === 'ambient') return 'ambient';
  if (k.length === 3) { if (last === 'fire') return 'fire'; if (last === 'knife' || last === 'knifeHeavy') return 'knife'; if (last === 'equip') return 'equip'; return 'foley'; }
  if (k[0] === 'impact') return /^footstep_/.test(last) ? 'step' : 'impact';
  if (k[0] === 'scifi') return 'ability';
  if (/^(kill\d|finisher)$/.test(last)) return 'kill';
  return { ui: 'ui', voice: 'voice', death: 'death', ability: 'ability', event: 'event', feedback: 'feedback' }[k[0]] || 'impact';
}
function build(rows) {
  const by = Object.fromEntries(rows.map((r) => [r.key, r])), files = {};
  for (const [key, f] of Object.entries(man.files)) {
    const r = by[key]; if (!r || r.error) throw Error('no audit row for ' + key);
    const ro = role(key), T = TARGET[ro === 'equip' ? 'foley' : ro];
    let g = T == null ? 0 : T - r.lufsM; g = g > 0 ? Math.min(g, 18, Math.max(0, 1 - r.peakDb)) : Math.max(g, -12);
    let o = 0; if (TRIM.has(ro) && r.leadMs > 5) o = Math.min((r.leadMs - 3) / 1000, Math.max(0, f.duration - 0.05));
    files[key] = { sha256: f.sha256, role: ro, lufs: r.lufsM, peak: r.peakDb, g: +g.toFixed(1), o: +o.toFixed(3) };
  }
  return { v: 1, note: 'generated by work/audio_levels_build.cjs from work/audio_asset_audit.cjs; g = playback gain dB, o = start trim s', target: TARGET, files };
}
if (require.main === module) {
  const rows = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
  const out = build(rows); fs.writeFileSync(path.join(root, 'audio/levels.json'), JSON.stringify(out, null, 1) + '\n');
  console.log('audio/levels.json', Object.keys(out.files).length);
}
module.exports = { build, role, TARGET };
